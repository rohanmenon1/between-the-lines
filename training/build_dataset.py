import argparse
import ast
import hashlib
import json
import re
from pathlib import Path
from typing import Any

from datasets import load_dataset


DEFAULT_DATASET = "code_search_net"
DEFAULT_CONFIG = "python"
DEFAULT_OUTPUT = Path("data/processed/codesearchnet_python_comments.jsonl")
DEFAULT_EVAL_OUTPUT = Path("data/eval/codesearchnet_python_comments_eval.jsonl")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build Python comment SFT data from CodeSearchNet.")
    parser.add_argument("--dataset", default=DEFAULT_DATASET)
    parser.add_argument("--config", default=DEFAULT_CONFIG)
    parser.add_argument("--split", default="train")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--eval-output", type=Path, default=DEFAULT_EVAL_OUTPUT)
    parser.add_argument("--limit", type=int, default=2000)
    parser.add_argument("--eval-size", type=int, default=100)
    parser.add_argument("--min-code-lines", type=int, default=3)
    parser.add_argument("--max-code-lines", type=int, default=40)
    parser.add_argument("--seed", type=int, default=42)
    return parser.parse_args()


def one_line(text: str) -> str:
    text = re.sub(r"\s+", " ", text.strip())
    return text


def normalize_docstring(text: str) -> str | None:
    text = one_line(text)
    if not text:
        return None

    if not text.isascii():
        return None

    noisy_markers = (
        "TODO",
        "FIXME",
        "http://",
        "https://",
        ":param",
        "@param",
        "Args:",
        "Returns:",
        " you ",
        "You ",
        " need ",
        " used is ",
        "Auto Generated",
        "autogenerated",
        "auto-generated",
    )
    if any(marker in text for marker in noisy_markers):
        return None

    text = re.split(r"(?<=[.!?])\s+", text, maxsplit=1)[0]
    text = text.strip("\"'` ")

    if ":" in text:
        return None

    if ";" in text:
        return None

    if "_" in text:
        return None

    if re.search(r"\b[A-Za-z_][A-Za-z0-9_]*\s*\(", text):
        return None

    if text.startswith("This "):
        return None

    if text.lower().endswith(("e.g.", "i.e.")):
        return None

    if len(text) < 12 or len(text) > 120:
        return None

    if not text:
        return None

    text = text[0].upper() + text[1:]
    if text[-1] not in ".!?":
        text += "."
    return text


def extract_docstring(row: dict[str, Any]) -> str | None:
    for key in ("docstring", "func_documentation_string", "documentation", "description"):
        value = row.get(key)
        if isinstance(value, str):
            normalized = normalize_docstring(value)
            if normalized:
                return normalized

    tokens = row.get("docstring_tokens")
    if isinstance(tokens, list):
        normalized = normalize_docstring(" ".join(str(token) for token in tokens))
        if normalized:
            return normalized

    return None


def extract_code(row: dict[str, Any]) -> str | None:
    for key in ("func_code_string", "code", "whole_func_string"):
        value = row.get(key)
        if isinstance(value, str) and value.strip():
            return value.strip()
    return None


def remove_leading_docstring(source: str) -> str | None:
    if not source.isascii():
        return None

    try:
        tree = ast.parse(source)
    except SyntaxError:
        return None

    if len(tree.body) != 1 or not isinstance(tree.body[0], (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
        return source

    node = tree.body[0]
    if not (
        node.body
        and isinstance(node.body[0], ast.Expr)
        and isinstance(node.body[0].value, ast.Constant)
        and isinstance(node.body[0].value.value, str)
    ):
        return source

    lines = source.splitlines()
    doc_node = node.body[0]
    if doc_node.end_lineno is None:
        return None

    del lines[doc_node.lineno - 1 : doc_node.end_lineno]
    return "\n".join(lines).strip()


def code_name_and_kind(source: str) -> tuple[str, str] | None:
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return None

    if len(tree.body) != 1:
        return None

    node = tree.body[0]
    if isinstance(node, ast.ClassDef):
        return "class", node.name
    if isinstance(node, ast.AsyncFunctionDef):
        return "async function", node.name
    if isinstance(node, ast.FunctionDef):
        return "function", node.name
    return None


def build_prompt(code: str) -> str:
    return (
        'Write exactly one concise Python comment starting with "# " for this code block.\n\n'
        "```python\n"
        f"{code.strip()}\n"
        "```\n"
    )


def make_id(code: str, comment: str) -> str:
    digest = hashlib.sha256(f"{code}\n{comment}".encode("utf-8")).hexdigest()
    return f"csn-py-{digest[:16]}"


def convert_row(row: dict[str, Any]) -> dict[str, Any] | None:
    code = extract_code(row)
    docstring = extract_docstring(row)
    if not code or not docstring:
        return None

    code = remove_leading_docstring(code)
    if not code:
        return None

    parsed = code_name_and_kind(code)
    if not parsed:
        return None

    line_count = len(code.splitlines())
    comment = f"# {docstring}"
    kind, name = parsed

    return {
        "id": make_id(code, comment),
        "language": "python",
        "comment_prefix": "# ",
        "kind": kind,
        "name": name,
        "code": code,
        "prompt": build_prompt(code),
        "completion": comment,
        "source": "code_search_net",
        "metadata": {
            "repo": row.get("repo"),
            "path": row.get("path"),
            "url": row.get("url"),
            "line_count": line_count,
        },
    }


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as file:
        for row in rows:
            file.write(json.dumps(row, ensure_ascii=True) + "\n")


def main() -> None:
    args = parse_args()
    dataset = load_dataset(args.dataset, args.config, split=args.split, trust_remote_code=True)
    dataset = dataset.shuffle(seed=args.seed)

    seen: set[str] = set()
    rows: list[dict[str, Any]] = []
    for raw_row in dataset:
        row = convert_row(raw_row)
        if not row:
            continue

        line_count = row["metadata"]["line_count"]
        if line_count < args.min_code_lines or line_count > args.max_code_lines:
            continue

        if row["id"] in seen:
            continue
        seen.add(row["id"])
        rows.append(row)

        if len(rows) >= args.limit + args.eval_size:
            break

    eval_rows = rows[: args.eval_size]
    train_rows = rows[args.eval_size :]

    write_jsonl(args.output, train_rows)
    write_jsonl(args.eval_output, eval_rows)

    print(f"Wrote {len(train_rows)} train rows to {args.output}")
    print(f"Wrote {len(eval_rows)} eval rows to {args.eval_output}")


if __name__ == "__main__":
    main()
